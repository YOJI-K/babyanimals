// 2文字の短い別名は、より長い語の一部に誤ヒットしやすい（例: 「公式サイト」「サイズ」「エキサイト」→ 種「サイ」）。
// 2026-07-27: 実際に「エキサイト」由来で存在しない「サイ」の赤ちゃんが生成されていたため恒久ガードを追加。
const SHORT_ALIAS_TRAPS: Record<string, RegExp> = {
  'サイ': /サイト|サイズ|サイン|サイエンス|サイクル|サイド|サイレン|サイコ|サイボーグ|エキサイト/g,
  'トラ': /トラック|トラブル|トラベル|トライ|トラム|トランス|トラクター|コントラ|イラスト|オーストラリア|ストラップ/g,
  'カバ': /カバー|カバン|カバチ/g,
  'ゾウ': /ゾウガメ|ゾウアザラシ|ゾウリムシ|ゾウムシ|ゾウキン/g,
  'ワニ': /ワニガメ/g,
  'ジャガー': /ジャガード/g,
  // 「パンダヤギ」「パンダマウス」は柄がパンダ柄なだけの別種（実データで誤判定を確認）
  'パンダ': /パンダヤギ|パンダマウス|パンダウサギ|パンダガメ/g,
};

export function extractSpeciesAlias(title: string): { species?: string; alias?: string } {
  for (const [alias, canonical] of SPECIES_MAP) {
    if (!title.includes(alias)) continue;
    const trap = SHORT_ALIAS_TRAPS[alias];
    if (trap) {
      // 罠語を取り除いてもなお別名が残る場合だけ採用する
      const cleaned = title.replace(new RegExp(trap.source, 'g'), '');
      if (!cleaned.includes(alias)) continue;
    }
    return { species: canonical, alias };
  }
  return {};
}
