import { test } from 'node:test';
import assert from 'node:assert/strict';
import { extractSpeciesAlias } from '../src/species.ts';

const sp = (t: string) => extractSpeciesAlias(t).species ?? null;

// --- 回帰防止：2文字の短い別名が長い語の一部に誤ヒットしないこと（2026-07-27） ---
// 「エキサイト」由来で存在しない「サイ」の赤ちゃんが実際に生成された事故の再発防止。
test('「エキサイト」を種サイと誤判定しない', () => {
  assert.equal(sp('日本モンキーセンターで赤ちゃん誕生 - Excite エキサイト'), null);
});
test('「公式サイト」を種サイと誤判定しない', () => {
  assert.equal(sp('赤ちゃん情報 - 平川動物公園公式サイト'), null);
});
test('「文字サイズ」を種サイと誤判定しない', () => {
  assert.equal(sp('文字サイズ・配色の変更'), null);
});
test('「サイズ発表」を種サイと誤判定しない', () => {
  assert.equal(sp('「ウシ科最大級」の赤ちゃんが誕生…規格外の大きさ・サイズ発表'), null);
});
test('「ゾウガメ」を種ゾウと誤判定しない', () => {
  assert.equal(sp('ゾウガメの赤ちゃんが孵化しました'), null);
});

// --- 正常系：本物の種名は今までどおり拾えること ---
test('本物の種名は従来どおり判定できる', () => {
  assert.equal(sp('サイの赤ちゃんが誕生しました'), 'サイ');
  assert.equal(sp('シロサイの赤ちゃんが誕生しました'), 'サイ');
  assert.equal(sp('アムールトラの赤ちゃん2頭が誕生'), 'トラ');
  assert.equal(sp('アジアゾウの赤ちゃんお披露目'), 'ゾウ');
  assert.equal(sp('コビトカバの赤ちゃん命名'), 'カバ');
});

// --- 2026-07-27 拡充分：順序依存（長い別名を先に判定）の回帰防止 ---
test('パンダは総称→ジャイアントパンダ、ただし修飾語つきは各種を優先', () => {
  assert.equal(sp('パンダの赤ちゃんが誕生しました'), 'ジャイアントパンダ');
  assert.equal(sp('レッサーパンダの赤ちゃん誕生'), 'レッサーパンダ');
  assert.equal(sp('ジャイアントパンダの双子が誕生'), 'ジャイアントパンダ');
});
test('「パンダヤギ」はパンダ柄の別種なので種を付けない', () => {
  assert.equal(sp('白黒模様の「パンダヤギ」赤ちゃん一般公開 伊東市の動物園'), null);
});
test('カワウソはコツメカワウソを優先する', () => {
  assert.equal(sp('コツメカワウソの赤ちゃん3頭が公開'), 'コツメカワウソ');
  assert.equal(sp('カワウソ赤ちゃん5匹、公開 とくしま動物園'), 'カワウソ');
});
test('修飾語つきの新規種は総称へ正規化する', () => {
  assert.equal(sp('フタユビナマケモノの赤ちゃんが誕生'), 'ナマケモノ');
  assert.equal(sp('オグロプレーリードッグの赤ちゃんが誕生しました'), 'プレーリードッグ');
  assert.equal(sp('エゾモモンガが誕生しました'), 'モモンガ');
  assert.equal(sp('シロテテナガザルの赤ちゃん'), 'テナガザル');
  assert.equal(sp('ホンドタヌキの赤ちゃん公開'), 'タヌキ');
});
test('今回追加した主要種を拾える', () => {
  assert.equal(sp('カピバラの赤ちゃんが誕生しました'), 'カピバラ');
  assert.equal(sp('マヌルネコの赤ちゃん公開'), 'マヌルネコ');
  assert.equal(sp('オカピの赤ちゃんが誕生'), 'オカピ');
  assert.equal(sp('アマミトゲネズミが繁殖しました'), 'アマミトゲネズミ');
});
test('「ジャガード」は種ジャガーと誤判定しない', () => {
  assert.equal(sp('ジャガード織のグッズが誕生'), null);
});

// --- 2026-08-07 追加：巡回復旧で実データに現れたが種が付かなかった2種 ---
test('2026-08-07 追加種を拾える（実データ由来）', () => {
  assert.equal(sp('オオツノヒツジの赤ちゃん公開'), 'オオツノヒツジ');
  assert.equal(sp('プーズーの赤ちゃんの名前投票を行います!'), 'プーズー');
  assert.equal(sp('プーズーの赤ちゃんがうまれました！'), 'プーズー');
});
test('2026-08-07 追加種が既存の判定を壊さない', () => {
  assert.equal(sp('アクシスジカの赤ちゃんが誕生'), 'シカ');
  assert.equal(sp('ヤクシカの赤ちゃんが誕生'), 'ヤクシカ');
  assert.equal(sp('ヒツジの毛刈りイベントを開催します'), null);
  assert.equal(sp('ヒツジ雲がきれいな一日でした'), null);
});
